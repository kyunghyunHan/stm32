/*
 * ============================================================
 * STM32 GPIO 입력 및 출력 회로 정리
 * ============================================================
 *
 * 대상 보드 : NUCLEO-F429ZI
 *
 * 외부 버튼 : D4 (PF14)
 * 외부 LED  : D2 (PF15)
 *
 * 주요 레지스터
 *
 * MODER  : GPIO 입력 / 출력 모드 설정
 * PUPDR  : 내부 Pull-up / Pull-down 저항 설정
 * OTYPER : Push-Pull / Open-Drain 출력 방식 설정
 * IDR    : GPIO 입력 상태 읽기
 * ODR    : GPIO 출력 상태 설정
 *
 *
 * ============================================================
 * 1. Pull-up (풀업) - 버튼을 누르면 LOW(0)
 * ============================================================
 *
 * [회로]
 *
 *          3.3V
 *            |
 *       [Pull-up 저항]
 *            |
 *            +------ PF14 (GPIO 입력)
 *            |
 *         [버튼]
 *            |
 *           GND
 *
 * [동작 원리]
 *
 * 1. 버튼을 누르지 않았을 때
 *    - 버튼이 열려 있다.
 *    - Pull-up 저항을 통해 GPIO 입력이 3.3V 쪽으로 연결된다.
 *    - PF14 입력 전압은 약 3.3V가 된다.
 *    - GPIO는 HIGH(1)로 인식한다.
 *
 * 2. 버튼을 눌렀을 때
 *    - 버튼이 닫힌다.
 *    - PF14가 GND에 연결된다.
 *    - PF14 입력 전압은 약 0V가 된다.
 *    - GPIO는 LOW(0)로 인식한다.
 *    - Pull-up 저항은 3.3V에서 GND로 흐르는 전류를 제한한다.
 *
 * [레지스터 설정]
 *
 * GPIOF_MODER &= ~(3U << 28);  // PF14 Input (00)
 *
 * GPIOF_PUPDR &= ~(3U << 28);
 * GPIOF_PUPDR |=  (1U << 28);  // Pull-up (01)
 *
 * [버튼 상태 확인]
 *
 * uint32_t button = (GPIOF_IDR >> 14) & 1U;
 *
 * if (button == 0U)
 * {
 *     // 버튼 눌림
 * }
 *
 * [실제 배선]
 *
 * D4(PF14) ---- 버튼 ---- GND
 *
 * 내부 Pull-up을 사용하므로 외부 Pull-up 저항은 필요 없다.
 *
 * 핵심:
 * 버튼 안 누름 = HIGH(1)
 * 버튼 누름    = LOW(0)
 *
 *
 * ============================================================
 * 2. Pull-down (풀다운) - 버튼을 누르면 HIGH(1)
 * ============================================================
 *
 * [회로]
 *
 *          3.3V
 *            |
 *         [버튼]
 *            |
 *            +------ PF14 (GPIO 입력)
 *            |
 *      [Pull-down 저항]
 *            |
 *           GND
 *
 * [동작 원리]
 *
 * 1. 버튼을 누르지 않았을 때
 *    - 버튼이 열려 있다.
 *    - Pull-down 저항을 통해 GPIO 입력이 GND 쪽으로 연결된다.
 *    - PF14 입력 전압은 약 0V가 된다.
 *    - GPIO는 LOW(0)로 인식한다.
 *
 * 2. 버튼을 눌렀을 때
 *    - 버튼이 닫힌다.
 *    - PF14가 3.3V에 연결된다.
 *    - PF14 입력 전압은 약 3.3V가 된다.
 *    - GPIO는 HIGH(1)로 인식한다.
 *    - Pull-down 저항을 통해 GND로 소량의 전류가 흐른다.
 *
 * [레지스터 설정]
 *
 * GPIOF_MODER &= ~(3U << 28);  // PF14 Input (00)
 *
 * GPIOF_PUPDR &= ~(3U << 28);
 * GPIOF_PUPDR |=  (2U << 28);  // Pull-down (10)
 *
 * [버튼 상태 확인]
 *
 * uint32_t button = (GPIOF_IDR >> 14) & 1U;
 *
 * if (button == 1U)
 * {
 *     // 버튼 눌림
 * }
 *
 * [실제 배선]
 *
 * 3.3V ---- 버튼 ---- D4(PF14)
 *
 * 내부 Pull-down을 사용하므로 외부 Pull-down 저항은 필요 없다.
 *
 * 핵심:
 * 버튼 안 누름 = LOW(0)
 * 버튼 누름    = HIGH(1)
 *
 *
 * ============================================================
 * 3. Push-Pull (푸시풀) - 출력 방식
 * ============================================================
 *
 * [내부 구조 - 개념도]
 *
 *              VDD (3.3V)
 *                  |
 *                PMOS
 *                  |
 *                  +------ GPIO 출력
 *                  |
 *                NMOS
 *                  |
 *                 GND
 *
 * [동작 원리]
 *
 * 1. ODR = 1
 *    - PMOS ON
 *    - NMOS OFF
 *    - GPIO가 HIGH(약 3.3V)를 출력한다.
 *    - 외부 부하에 전류를 공급(Source)할 수 있다.
 *
 * 2. ODR = 0
 *    - PMOS OFF
 *    - NMOS ON
 *    - GPIO가 LOW(약 0V)를 출력한다.
 *    - 외부 부하의 전류를 GND로 흘릴(Sink) 수 있다.
 *
 * [레지스터 설정]
 *
 * GPIOF_MODER &= ~(3U << 30);
 * GPIOF_MODER |=  (1U << 30); // PF15 Output (01)
 *
 * GPIOF_OTYPER &= ~(1U << 15); // Push-Pull (0)
 *
 * [출력 제어]
 *
 * GPIOF_ODR |=  (1U << 15); // HIGH 출력
 * GPIOF_ODR &= ~(1U << 15); // LOW 출력
 *
 * [Active-High LED 회로]
 *
 * PF15 ---- 330Ω ---- LED(+) LED(-) ---- GND
 *
 * HIGH(1) = LED ON
 * LOW(0)  = LED OFF
 *
 * 주의:
 * Push-Pull에서도 LED를 3.3V와 GPIO 사이에 연결하면
 * LOW일 때 LED가 켜지는 Active-Low 회로를 만들 수 있다.
 *
 *
 * ============================================================
 * 4. Open-Drain (오픈드레인) - 출력 방식
 * ============================================================
 *
 * [내부 구조 - 개념도]
 *
 *             GPIO 출력
 *                 |
 *               NMOS
 *                 |
 *                GND
 *
 * Push-Pull과 달리 GPIO를 VDD에 직접 연결하는
 * 상단 출력 트랜지스터를 사용하지 않는다.
 *
 * [동작 원리]
 *
 * 1. ODR = 0
 *    - NMOS ON
 *    - GPIO가 GND 쪽으로 연결된다.
 *    - GPIO 출력은 LOW가 된다.
 *    - 외부 회로의 전류를 GND로 흘릴 수 있다.
 *
 * 2. ODR = 1
 *    - NMOS OFF
 *    - GPIO 출력이 해제된다.
 *    - GPIO는 Hi-Z(High Impedance) 상태가 된다.
 *    - GPIO 자체가 HIGH 전압을 공급하지 않는다.
 *    - Pull-up 저항 등 외부 회로가 있으면 HIGH가 될 수 있다.
 *
 * [레지스터 설정]
 *
 * GPIOF_MODER &= ~(3U << 30);
 * GPIOF_MODER |=  (1U << 30); // PF15 Output (01)
 *
 * GPIOF_OTYPER |= (1U << 15); // Open-Drain (1)
 *
 * [출력 제어]
 *
 * GPIOF_ODR &= ~(1U << 15); // LOW 출력
 * GPIOF_ODR |=  (1U << 15); // 출력 해제 (Hi-Z)
 *
 *
 * ============================================================
 * 5. Open-Drain + Active-Low LED 회로
 * ============================================================
 *
 * [회로]
 *
 *            3.3V
 *              |
 *            [330Ω]
 *              |
 *           LED (+)
 *           LED (-)
 *              |
 *            PF15
 *              |
 *          내부 NMOS
 *              |
 *             GND
 *
 * [동작 원리]
 *
 * 1. ODR = 0
 *    - NMOS가 ON 된다.
 *    - PF15가 LOW로 내려간다.
 *    - 3.3V → 저항 → LED → PF15 → NMOS → GND
 *    - 전류가 흐르므로 LED가 켜진다.
 *
 * 2. ODR = 1
 *    - NMOS가 OFF 된다.
 *    - PF15는 Hi-Z 상태가 된다.
 *    - LED를 통과하는 정상적인 전류 경로가 끊긴다.
 *    - LED가 꺼진다.
 *
 * [실제 배선]
 *
 * 3.3V ---- 330Ω ---- LED(+) LED(-) ---- D2(PF15)
 *
 * [출력 제어]
 *
 * GPIOF_ODR &= ~(1U << 15); // LED ON
 * GPIOF_ODR |=  (1U << 15); // LED OFF
 *
 * 핵심:
 * LOW(0) = LED ON
 * ODR 1  = Hi-Z, LED OFF
 *
 *
 * ============================================================
 * 6. 핵심 레지스터 차이
 * ============================================================
 *
 * MODER
 *   00 = Input
 *   01 = Output
 *   10 = Alternate Function
 *   11 = Analog
 *
 * PUPDR
 *   00 = No Pull-up / Pull-down
 *   01 = Pull-up
 *   10 = Pull-down
 *   11 = Reserved
 *
 * OTYPER
 *   0 = Push-Pull
 *   1 = Open-Drain
 *
 * IDR
 *   GPIO 입력 핀의 논리 상태 읽기
 *
 * ODR
 *   GPIO 출력 데이터 설정
 *
 *
 * ============================================================
 * 7. 최종 핵심 정리
 * ============================================================
 *
 * [입력]
 *
 * Pull-up:
 *   버튼 → GND 연결
 *   PUPDR = 01
 *   누르면 0
 *
 * Pull-down:
 *   버튼 → 3.3V 연결
 *   PUPDR = 10
 *   누르면 1
 *
 * [출력]
 *
 * Push-Pull:
 *   OTYPER = 0
 *   HIGH와 LOW를 직접 출력
 *
 * Open-Drain:
 *   OTYPER = 1
 *   LOW 출력 또는 Hi-Z
 *
 * [LED]
 *
 * Active-High:
 *   GPIO → 저항 → LED → GND
 *   HIGH = ON
 *
 * Active-Low:
 *   3.3V → 저항 → LED → GPIO
 *   LOW = ON
 *
 * [주의사항]
 *
 * 1. 버튼은 입력이므로 PUPDR로 기본 전압을 설정한다.
 * 2. OTYPER는 출력 드라이버 방식만 설정한다.
 * 3. LED의 Active-High / Active-Low는 회로 연결로 결정된다.
 * 4. Floating 방지를 위해 입력의 기본 전압을 정해야 한다.
 * 5. 외부 LED에는 전류 제한 저항을 사용한다.
 * 6. 외부 버튼의 접점 튐(Bouncing)은 별도 처리해야 한다.
 * 7. 회로 배선을 변경할 때는 보드 전원을 끈다.
 *
 * 핵심:
 *
 * 입력  : MODER + PUPDR + IDR
 * 출력  : MODER + OTYPER + ODR
 *
 * Pull-up / Pull-down = 입력 전압의 기본 상태 결정
 * Push-Pull / Open-Drain = 출력 드라이버 동작 방식 결정
 * Active-High / Active-Low = 회로의 활성 논리 결정
 *
 * ============================================================
 */

 